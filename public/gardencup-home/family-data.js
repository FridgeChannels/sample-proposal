// A time-of-day preset chooses where each personal story begins. It does not
// schedule later group moves. Next-task timing always belongs to that resident.
function preset(id,title,steps,dialogue){
 const participants=Object.fromEntries(dailyStories.map((story,actor)=>{
  const first=steps[actor]||0,ordered=story.tasks.map((_,i)=>story.tasks[(first+i)%story.tasks.length]);
  return [actor,{...ordered[0],next:ordered.slice(1),offset:story.offset,storyId:story.id,purpose:story.purpose}];
 }));
 return {id,title,participants,independent:true,duration:600,lines:dialogue.map(([actor,text],i)=>({actor,text,kind:'dialogue',at:2+i*11}))};
}
